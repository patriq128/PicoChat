def chatroom():
    def sender_print(text):
        print(f"\033[34m● {sender_name} >>\033[0m {text}")

    def user_print(text):
        print(f"\033[31m● You >>\033[0m {text}")

    messages = []
    while True:
        print("\033[2J\033[H", end="")
        for i in messages:
            if i["type"] == "user":
                user_print(i["text"])
            elif i["type"] == "sender":
                sender_print(i["text"])

        print("------------------------------------------")
        text = input(">> ")
        user_type = "user"
        data = {"type": user_type, "text": text}
        messages.append(data)

class Config():
    def load(self):
        try:
            with open("config.json", "r") as f:
                data = json.load(f)
        except:
            open("config.json", "w").close()
            data = {}

        return data
    
    def save(self, data):
        with open("config.json", "w") as f:
            json.dump(data, f)

    def basic(self):
        print("Config")
        ip = input("IP of the server: ")
        username = input("Your username: ")
        data = {"ip": ip, "username":username}
        self.save(data)

config = Config()

def main():
    booting_page()
