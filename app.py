def chatroom():
    def sender(text):
        print(f"\033[34m● {sender_name} >>\033[0m {text}")

    def user(text):
        print(f"\033[31m● You >>\033[0m {text}")

    messages = []
    while True:
        print("\033[2J\033[H", end="")
        for i in messages:
            if i["type"] == "user":
                user(i["text"])
            elif i["type"] == "sender":
                sender(i["text"])

        print("------------------------------------------")
        text = input(">> ")
        user_type = "user"
        data = {"type": user_type, "text": text}
        messages.append(data)


